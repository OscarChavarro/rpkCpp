/**
Persistence of high dynamic range images in the RGBE format of Greg Ward's
Radiance system (files usually named .pic or .hdr), used through the
`ImagePersistence` front end.

Each pixel is stored in 4 bytes: three 8 bit mantissas (red, green, blue)
sharing one 8 bit exponent, so unbounded floating point values (e.g.
radiances) keep about 1% of relative precision over a range of 76 orders of
magnitude. The file is a text header followed by the scanlines from top to
bottom; each scanline is run length encoded component by component ("new"
RLE of Radiance) when its width is in [8, 32767], or stored flat otherwise.

The export writes the header
    #?RADIANCE
    # Image generated by VitralSDK (https://github.com/OscarChavarro/vitral)
    FORMAT=32-bit_rle_rgbe
    (empty line)
    -Y <height> +X <width>
The import reads the flat, the "old" (repeat counts) and the "new" run length
encodings, for the standard -Y +X orientation only.

The encoder derives from RenderPark's dkcolor.c (Philippe Bekaert, Jan
Prikryl and Olaf Appeltants, 1998 - 2000), itself based on Radiance's
color.c (Greg Ward, 1985).

Bytes are kept as int values in [0, 255] (Java's byte is signed).

Translation of `java/base/src/main/vsdk/toolkit/io/image/ImagePersistenceRgbe.java`:
Java's `int[]` and `byte[]` are an `Int32Array` and a `Uint8Array` (the
written bytes are the same), accessed through `JavaArray` for Java's bounds
checks, and the `throws Exception` methods propagate the exceptions of the
streams.
*/
export class ImagePersistenceRgbe extends PersistenceElement {
    private static readonly RED = 0;
    private static readonly GREEN = 1;
    private static readonly BLUE = 2;
    private static readonly EXPONENT = 3;
    private static readonly BYTES_PER_PIXEL = 4;
    private static readonly EXPONENT_EXCESS = 128;
    private static readonly MINIMUM_ENCODED_SCANLINE_LENGTH = 8;
    private static readonly MAXIMUM_ENCODED_SCANLINE_LENGTH = 0x7fff;
    private static readonly MINIMUM_RUN_LENGTH = 4;

    private constructor() {
        super();
    }

    private static writeHeader(os: OutputStream, width: number, height: number): void {
        const header =
            "#?RADIANCE\n" +
            "# Image generated by VitralSDK (https://github.com/OscarChavarro/vitral)\n" +
            "FORMAT=32-bit_rle_rgbe\n" +
            "\n" +
            "-Y " +
            height +
            " +X " +
            width +
            "\n";
        PersistenceElement.writeBytes(os, new TextEncoder().encode(header));
    }

    /**
    Converts a color to RGBE: the mantissas share the exponent of the largest
    component. Colors whose largest component is at most 1e-32 (black, or with
    all components negative) are stored as zero, and so are negative components.
    */
    private static rgbToRgbe(rgbe: Int32Array, offset: number, r: number, g: number, b: number): void {
        const C = ImagePersistenceRgbe;
        let d = r > g ? r : g;
        if (b > d) {
            d = b;
        }

        if (!(d > 1e-32)) {
            JavaArray.set(rgbe, offset + C.RED, 0);
            JavaArray.set(rgbe, offset + C.GREEN, 0);
            JavaArray.set(rgbe, offset + C.BLUE, 0);
            JavaArray.set(rgbe, offset + C.EXPONENT, 0);
            return;
        }

        // d = mantissa * 2^e, with mantissa in [0.5, 1); compared before adding
        // one, as the exponent of an infinite d is the largest int
        let e = JavaMath.getExponent(d);
        if (e >= 255 - C.EXPONENT_EXCESS) {
            // Too large for the exponent byte: the brightest representable value
            JavaArray.set(rgbe, offset + C.RED, 255);
            JavaArray.set(rgbe, offset + C.GREEN, 255);
            JavaArray.set(rgbe, offset + C.BLUE, 255);
            JavaArray.set(rgbe, offset + C.EXPONENT, 255);
            return;
        }
        e++;
        const mantissa = JavaMath.scalb(d, -e);
        d = (mantissa * 255.9999) / d;

        JavaArray.set(rgbe, offset + C.RED, r > 0.0 ? javaIntCast(r * d) & 0xff : 0);
        JavaArray.set(rgbe, offset + C.GREEN, g > 0.0 ? javaIntCast(g * d) & 0xff : 0);
        JavaArray.set(rgbe, offset + C.BLUE, b > 0.0 ? javaIntCast(b * d) & 0xff : 0);
        JavaArray.set(rgbe, offset + C.EXPONENT, (e + C.EXPONENT_EXCESS) & 0xff);
    }

    /**
    Inverse of rgbToRgbe, at the center of the interval of the mantissa
    */
    private static rgbeComponentToDouble(mantissa: number, exponent: number): number {
        if (exponent === 0) {
            return 0.0;
        }
        return (mantissa + 0.5) * JavaMath.scalb(1.0, exponent - (ImagePersistenceRgbe.EXPONENT_EXCESS + 8));
    }

    /**
    Writes a scanline of RGBE pixels: run length encoded by component when its
    width allows it, flat otherwise
    */
    private static writeScanline(os: OutputStream, scanline: Int32Array, width: number): void {
        const C = ImagePersistenceRgbe;
        if (width < C.MINIMUM_ENCODED_SCANLINE_LENGTH || width > C.MAXIMUM_ENCODED_SCANLINE_LENGTH) {
            const flat = new Uint8Array(Math.imul(C.BYTES_PER_PIXEL, width));
            for (let k = 0; k < flat.length; k++) {
                JavaArray.set(flat, k, JavaArray.get(scanline, k) & 0xff);
            }
            PersistenceElement.writeBytes(os, flat);
            return;
        }

        // A component takes at most 2 bytes per pixel plus one: each run (of at
        // least 2 pixels) takes 2 bytes, and each non-run one byte more than its
        // pixels, with at most one non-run more than runs
        const encoded = new Uint8Array(4 + Math.imul(C.BYTES_PER_PIXEL, 2 * width + 1));
        let n = 0;

        // Magic header
        JavaArray.set(encoded, n++, 2);
        JavaArray.set(encoded, n++, 2);
        JavaArray.set(encoded, n++, (width >> 8) & 0xff);
        JavaArray.set(encoded, n++, width & 255);

        // Components separately
        for (let i = 0; i < C.BYTES_PER_PIXEL; i++) {
            let count = 0;
            for (let j = 0; j < width; j += count) {
                // Find next run
                let begin: number;
                for (begin = j; begin < width; begin += count) {
                    for (
                        count = 1;
                        count < 127 &&
                        begin + count < width &&
                        JavaArray.get(scanline, Math.imul(begin + count, C.BYTES_PER_PIXEL) + i) ===
                            JavaArray.get(scanline, Math.imul(begin, C.BYTES_PER_PIXEL) + i);
                        count++
                    ) {
                        // Empty loop body: the condition counts the run
                    }
                    if (count >= C.MINIMUM_RUN_LENGTH) {
                        // Long enough
                        break;
                    }
                }

                if (begin - j > 1 && begin - j < C.MINIMUM_RUN_LENGTH) {
                    let c2 = j + 1;
                    while (
                        JavaArray.get(scanline, Math.imul(c2++, C.BYTES_PER_PIXEL) + i) ===
                        JavaArray.get(scanline, Math.imul(j, C.BYTES_PER_PIXEL) + i)
                    ) {
                        if (c2 === begin) {
                            // Short run
                            JavaArray.set(encoded, n++, (128 + begin - j) & 0xff);
                            JavaArray.set(
                                encoded,
                                n++,
                                JavaArray.get(scanline, Math.imul(j, C.BYTES_PER_PIXEL) + i) & 0xff,
                            );
                            j = begin;
                            break;
                        }
                    }
                }
                while (j < begin) {
                    // Non-run
                    let c2 = begin - j;
                    if (c2 > 128) {
                        c2 = 128;
                    }
                    JavaArray.set(encoded, n++, c2 & 0xff);
                    while (c2-- > 0) {
                        JavaArray.set(
                            encoded,
                            n++,
                            JavaArray.get(scanline, Math.imul(j++, C.BYTES_PER_PIXEL) + i) & 0xff,
                        );
                    }
                }
                if (count >= C.MINIMUM_RUN_LENGTH) {
                    // Run
                    JavaArray.set(encoded, n++, (128 + count) & 0xff);
                    JavaArray.set(
                        encoded,
                        n++,
                        JavaArray.get(scanline, Math.imul(begin, C.BYTES_PER_PIXEL) + i) & 0xff,
                    );
                } else {
                    count = 0;
                }
            }
        }

        os.writeBytes(encoded, 0, n);
    }

    /**
    Writes the image in RGBE format on the given stream (which is not closed).
    Components below zero are written as zero.
    @param os
    @param image
    @return true if the image could be written, false otherwise
    @throws Exception when the stream fails
    */
    public static exportRgbe(os: OutputStream, image: RGBImageFloatUncompressed | null): boolean {
        const C = ImagePersistenceRgbe;
        if (image === null || image.getXSize() <= 0 || image.getYSize() <= 0) {
            return false;
        }

        const width = image.getXSize();
        const height = image.getYSize();
        C.writeHeader(os, width, height);

        const scanline = new Int32Array(Math.imul(C.BYTES_PER_PIXEL, width));
        for (let y = 0; y < height; y++) {
            for (let x = 0; x < width; x++) {
                const color = image.getPixel(x, y);
                C.rgbToRgbe(scanline, Math.imul(x, C.BYTES_PER_PIXEL), color.getR(), color.getG(), color.getB());
            }
            C.writeScanline(os, scanline, width);
        }
        return true;
    }

    private static readFully(is: InputStream, buffer: Int32Array, offset: number, length: number): boolean {
        for (let k = 0; k < length; k++) {
            const value = is.read();
            if (value < 0) {
                return false;
            }
            JavaArray.set(buffer, offset + k, value);
        }
        return true;
    }

    /**
    Reads a header line without its end of line. null at the end of the stream
    or for a line longer than the given capacity.
    */
    private static readHeaderLine(is: InputStream, capacity: number): string | null {
        let line = "";
        while (true) {
            const c = is.read();
            if (c < 0) {
                return null;
            }
            if (c === 0x0a) {
                break;
            }
            if (line.length >= capacity - 1) {
                return null;
            }
            line += globalThis.String.fromCharCode(c & 0xffff);
        }
        return line;
    }

    /**
    Parses a non negative decimal integer of `line` starting at `position[0]`,
    leaving `position[0]` after its last digit. Returns Integer.MIN_VALUE when
    there is no digit at that position.
    */
    private static parseInteger(line: string, position: Int32Array): number {
        let p = JavaArray.get(position, 0);
        let sign = 1;
        if (p < line.length && (line.charAt(p) === "+" || line.charAt(p) === "-")) {
            if (line.charAt(p) === "-") {
                sign = -1;
            }
            p++;
        }
        const start = p;
        let value = 0;
        while (p < line.length && Character.isDigit(line.charAt(p)) && value <= Integer.MAX_VALUE) {
            value = value * 10 + (line.charCodeAt(p) - 0x30);
            p++;
        }
        if (p === start || value > Integer.MAX_VALUE) {
            return Integer.MIN_VALUE;
        }
        JavaArray.set(position, 0, p);
        return sign * value;
    }

    private static skipSpaces(line: string, p: number): number {
        while (p < line.length && Character.isWhitespace(line.charAt(p))) {
            p++;
        }
        return p;
    }

    /**
    Reads the header, returning {width, height}, or null if it is not an RGBE
    header with the -Y +X orientation
    */
    private static readHeader(is: InputStream): Int32Array | null {
        const C = ImagePersistenceRgbe;
        let line = C.readHeaderLine(is, 1024);
        if (line === null || !line.startsWith("#?")) {
            return null;
        }

        // Variables up to the empty line
        while (true) {
            line = C.readHeaderLine(is, 1024);
            if (line === null) {
                return null;
            }
            if (line.length === 0) {
                break;
            }
            if (line.startsWith("FORMAT=") && line.substring(7) !== "32-bit_rle_rgbe") {
                return null;
            }
        }

        // Resolution: "-Y %d +X %d" with nothing after it
        line = C.readHeaderLine(is, 1024);
        if (line === null) {
            return null;
        }
        const position = new Int32Array(1);
        let p = C.skipSpaces(line, 0);
        if (!line.startsWith("-Y", p)) {
            return null;
        }
        JavaArray.set(position, 0, C.skipSpaces(line, p + 2));
        const height = C.parseInteger(line, position);
        if (height === Integer.MIN_VALUE) {
            return null;
        }
        p = C.skipSpaces(line, JavaArray.get(position, 0));
        if (!line.startsWith("+X", p)) {
            return null;
        }
        JavaArray.set(position, 0, C.skipSpaces(line, p + 2));
        const width = C.parseInteger(line, position);
        if (width === Integer.MIN_VALUE || JavaArray.get(position, 0) !== line.length) {
            return null;
        }
        if (width <= 0 || height <= 0) {
            return null;
        }
        return Int32Array.of(width, height);
    }

    /** Java's `System.arraycopy` over two `int[]` (the ranges never overlap here) */
    private static arraycopy(src: Int32Array, srcPos: number, dest: Int32Array, destPos: number, length: number): void {
        for (let k = 0; k < length; k++) {
            JavaArray.set(dest, destPos + k, JavaArray.get(src, srcPos + k));
        }
    }

    /**
    Reads the rest of a flat scanline, whose first pixel is already in
    `scanline`. As in Radiance, a pixel with r = g = b = 1 after the first one is
    an "old" run length encoded repeat count of the previous pixel (shifted by 8
    bits for each consecutive count).
    */
    private static readOldScanline(is: InputStream, scanline: Int32Array, width: number): boolean {
        const C = ImagePersistenceRgbe;
        let shift = 0;
        let x = 1;
        while (x < width) {
            const pixel = Math.imul(x, C.BYTES_PER_PIXEL);
            if (!C.readFully(is, scanline, pixel, C.BYTES_PER_PIXEL)) {
                return false;
            }
            if (
                JavaArray.get(scanline, pixel + C.RED) === 1 &&
                JavaArray.get(scanline, pixel + C.GREEN) === 1 &&
                JavaArray.get(scanline, pixel + C.BLUE) === 1
            ) {
                // Java's long shift: exact in a double for shift <= 24
                let repeat = JavaArray.get(scanline, pixel + C.EXPONENT) * 2 ** shift;
                if (shift > 24 || repeat > width - x) {
                    return false;
                }
                for (; repeat > 0; repeat--) {
                    C.arraycopy(
                        scanline,
                        Math.imul(x - 1, C.BYTES_PER_PIXEL),
                        scanline,
                        Math.imul(x, C.BYTES_PER_PIXEL),
                        C.BYTES_PER_PIXEL,
                    );
                    x++;
                }
                shift += 8;
            } else {
                shift = 0;
                x++;
            }
        }
        return true;
    }

    private static readScanline(is: InputStream, scanline: Int32Array, width: number): boolean {
        const C = ImagePersistenceRgbe;
        if (width < C.MINIMUM_ENCODED_SCANLINE_LENGTH || width > C.MAXIMUM_ENCODED_SCANLINE_LENGTH) {
            if (!C.readFully(is, scanline, 0, C.BYTES_PER_PIXEL)) {
                return false;
            }
            return C.readOldScanline(is, scanline, width);
        }

        const start = new Int32Array(C.BYTES_PER_PIXEL);
        if (!C.readFully(is, start, 0, C.BYTES_PER_PIXEL)) {
            return false;
        }
        if (JavaArray.get(start, 0) !== 2 || JavaArray.get(start, 1) !== 2 || (JavaArray.get(start, 2) & 0x80) !== 0) {
            // Not run length encoded by component: a flat (or old) scanline
            C.arraycopy(start, 0, scanline, 0, C.BYTES_PER_PIXEL);
            return C.readOldScanline(is, scanline, width);
        }
        if (((JavaArray.get(start, 2) << 8) | JavaArray.get(start, 3)) !== width) {
            return false;
        }

        for (let i = 0; i < C.BYTES_PER_PIXEL; i++) {
            let x = 0;
            while (x < width) {
                const code = is.read();
                if (code <= 0) {
                    return false;
                }
                if (code > 128) {
                    // Run
                    const count = code - 128;
                    const value = is.read();
                    if (value < 0 || count > width - x) {
                        return false;
                    }
                    for (let k = 0; k < count; k++) {
                        JavaArray.set(scanline, Math.imul(x++, C.BYTES_PER_PIXEL) + i, value);
                    }
                } else {
                    // Non-run
                    if (code > width - x) {
                        return false;
                    }
                    for (let k = 0; k < code; k++) {
                        const value = is.read();
                        if (value < 0) {
                            return false;
                        }
                        JavaArray.set(scanline, Math.imul(x++, C.BYTES_PER_PIXEL) + i, value);
                    }
                }
            }
        }
        return true;
    }

    /**
    Reads an RGBE image from the given stream (which is not closed).
    @param is
    @return the image, or null if the stream does not hold an RGBE image this
    class can read
    @throws Exception when the stream fails
    */
    public static importRgbe(is: InputStream): RGBImageFloatUncompressed | null {
        const C = ImagePersistenceRgbe;
        const size = C.readHeader(is);
        if (size === null) {
            return null;
        }
        const width = JavaArray.get(size, 0);
        const height = JavaArray.get(size, 1);

        const image = new RGBImageFloatUncompressed();
        if (!image.initNoFill(width, height)) {
            return null;
        }

        const scanline = new Int32Array(Math.imul(C.BYTES_PER_PIXEL, width));
        for (let y = 0; y < height; y++) {
            if (!C.readScanline(is, scanline, width)) {
                return null;
            }
            for (let x = 0; x < width; x++) {
                const pixel = Math.imul(x, C.BYTES_PER_PIXEL);
                const exponent = JavaArray.get(scanline, pixel + C.EXPONENT);
                image.putPixel(
                    x,
                    y,
                    C.rgbeComponentToDouble(JavaArray.get(scanline, pixel + C.RED), exponent),
                    C.rgbeComponentToDouble(JavaArray.get(scanline, pixel + C.GREEN), exponent),
                    C.rgbeComponentToDouble(JavaArray.get(scanline, pixel + C.BLUE), exponent),
                );
            }
        }
        return image;
    }
}
