#ifndef __IMAGE_PERSISTENCE_RGBE__
#define __IMAGE_PERSISTENCE_RGBE__

#include "java/io/InputStream.h"
#include "java/io/OutputStream.h"
#include "vsdk/toolkit/io/PersistenceElement.h"
class RGBImageFloatUncompressed;

/**
Persistence of high dynamic range images in the RGBE format of Greg Ward's
Radiance system (files usually named .pic or .hdr), used through the
`ImagePersistence` front end.

Each pixel is stored in 4 bytes: three 8 bit mantissas (red, green, blue)
sharing one 8 bit exponent, so unbounded floating point values (e.g.
radiances) keep about 1% of relative precision over a range of 76 orders of
magnitude. The file is a text header followed by the scanlines from top to
bottom; each scanline is run length encoded component by component ("new"
RLE of Radiance) when its width is in [8, 32767], or stored flat otherwise.

The export writes the header
    #?RADIANCE
    # Image generated by VitralSDK (https://github.com/OscarChavarro/vitral)
    FORMAT=32-bit_rle_rgbe
    (empty line)
    -Y <height> +X <width>
The import reads the flat, the "old" (repeat counts) and the "new" run length
encodings, for the standard -Y +X orientation only.

The encoder derives from RenderPark's dkcolor.c (Philippe Bekaert, Jan
Prikryl and Olaf Appeltants, 1998 - 2000), itself based on Radiance's
color.c (Greg Ward, 1985).
*/
class ImagePersistenceRgbe : public PersistenceElement {
  private:
    static constexpr int RED = 0;
    static constexpr int GREEN = 1;
    static constexpr int BLUE = 2;
    static constexpr int EXPONENT = 3;
    static constexpr int BYTES_PER_PIXEL = 4;
    static constexpr int EXPONENT_EXCESS = 128;
    static constexpr int MINIMUM_ENCODED_SCANLINE_LENGTH = 8;
    static constexpr int MAXIMUM_ENCODED_SCANLINE_LENGTH = 0x7fff;
    static constexpr int MINIMUM_RUN_LENGTH = 4;

    ImagePersistenceRgbe() {}

    static void writeHeader(java::OutputStream &os, int width, int height);
    static void rgbToRgbe(unsigned char *rgbe, double r, double g, double b);
    static double rgbeComponentToDouble(int mantissa, int exponent);
    static void writeScanline(java::OutputStream &os, const unsigned char *scanline, int width);

    static bool readFully(java::InputStream &is, unsigned char *buffer, int length);
    static bool readHeaderLine(java::InputStream &is, char *line, int capacity);
    static bool readHeader(java::InputStream &is, int *width, int *height);
    static bool readOldScanline(java::InputStream &is, unsigned char *scanline, int width);
    static bool readScanline(java::InputStream &is, unsigned char *scanline, int width);

  public:
    /**
    Writes the image in RGBE format on the given stream (which is not closed).
    Components below zero are written as zero.
    @return true if the image could be written, false otherwise
    */
    static bool exportRgbe(java::OutputStream &os, const RGBImageFloatUncompressed *image);

    /**
    Reads an RGBE image from the given stream (which is not closed).
    @return the image, to be deleted by the caller, or nullptr if the stream
    does not hold an RGBE image this class can read
    */
    static RGBImageFloatUncompressed *importRgbe(java::InputStream &is);
};

#endif
