package vsdk.toolkit.io.image;

import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;

import vsdk.toolkit.common.color.ColorRgb;
import vsdk.toolkit.io.PersistenceElement;
import vsdk.toolkit.media.RGBImageFloatUncompressed;

/**
Persistence of high dynamic range images in the RGBE format of Greg Ward's
Radiance system (files usually named .pic or .hdr), used through the
`ImagePersistence` front end.

Each pixel is stored in 4 bytes: three 8 bit mantissas (red, green, blue)
sharing one 8 bit exponent, so unbounded floating point values (e.g.
radiances) keep about 1% of relative precision over a range of 76 orders of
magnitude. The file is a text header followed by the scanlines from top to
bottom; each scanline is run length encoded component by component ("new"
RLE of Radiance) when its width is in [8, 32767], or stored flat otherwise.

The export writes the header
    #?RADIANCE
    # Image generated by VitralSDK (https://github.com/OscarChavarro/vitral)
    FORMAT=32-bit_rle_rgbe
    (empty line)
    -Y <height> +X <width>
The import reads the flat, the "old" (repeat counts) and the "new" run length
encodings, for the standard -Y +X orientation only.

The encoder derives from RenderPark's dkcolor.c (Philippe Bekaert, Jan
Prikryl and Olaf Appeltants, 1998 - 2000), itself based on Radiance's
color.c (Greg Ward, 1985).

Bytes are kept as int values in [0, 255] (Java's byte is signed).
*/
public class ImagePersistenceRgbe extends PersistenceElement
{
    private static final int RED = 0;
    private static final int GREEN = 1;
    private static final int BLUE = 2;
    private static final int EXPONENT = 3;
    private static final int BYTES_PER_PIXEL = 4;
    private static final int EXPONENT_EXCESS = 128;
    private static final int MINIMUM_ENCODED_SCANLINE_LENGTH = 8;
    private static final int MAXIMUM_ENCODED_SCANLINE_LENGTH = 0x7fff;
    private static final int MINIMUM_RUN_LENGTH = 4;

    private ImagePersistenceRgbe()
    {
    }

    private static void writeHeader(OutputStream os, int width, int height)
        throws Exception
    {
        String header =
            "#?RADIANCE\n" +
            "# Image generated by VitralSDK (https://github.com/OscarChavarro/vitral)\n" +
            "FORMAT=32-bit_rle_rgbe\n" +
            "\n" +
            "-Y " + height + " +X " + width + "\n";
        writeBytes(os, header.getBytes(StandardCharsets.US_ASCII));
    }

    /**
    Converts a color to RGBE: the mantissas share the exponent of the largest
    component. Colors whose largest component is at most 1e-32 (black, or with
    all components negative) are stored as zero, and so are negative components.
    */
    private static void rgbToRgbe(int[] rgbe, int offset, double r, double g, double b)
    {
        double d = r > g ? r : g;
        if ( b > d ) {
            d = b;
        }

        if ( !(d > 1e-32) ) {
            rgbe[offset + RED] = 0;
            rgbe[offset + GREEN] = 0;
            rgbe[offset + BLUE] = 0;
            rgbe[offset + EXPONENT] = 0;
            return;
        }

        // d = mantissa * 2^e, with mantissa in [0.5, 1); compared before adding
        // one, as the exponent of an infinite d is the largest int
        int e = Math.getExponent(d);
        if ( e >= 255 - EXPONENT_EXCESS ) {
            // Too large for the exponent byte: the brightest representable value
            rgbe[offset + RED] = 255;
            rgbe[offset + GREEN] = 255;
            rgbe[offset + BLUE] = 255;
            rgbe[offset + EXPONENT] = 255;
            return;
        }
        e++;
        double mantissa = Math.scalb(d, -e);
        d = mantissa * 255.9999 / d;

        rgbe[offset + RED] = r > 0.0 ? ((int)(r * d)) & 0xFF : 0;
        rgbe[offset + GREEN] = g > 0.0 ? ((int)(g * d)) & 0xFF : 0;
        rgbe[offset + BLUE] = b > 0.0 ? ((int)(b * d)) & 0xFF : 0;
        rgbe[offset + EXPONENT] = (e + EXPONENT_EXCESS) & 0xFF;
    }

    /**
    Inverse of rgbToRgbe, at the center of the interval of the mantissa
    */
    private static double rgbeComponentToDouble(int mantissa, int exponent)
    {
        if ( exponent == 0 ) {
            return 0.0;
        }
        return ((double)mantissa + 0.5) * Math.scalb(1.0, exponent - (EXPONENT_EXCESS + 8));
    }

    /**
    Writes a scanline of RGBE pixels: run length encoded by component when its
    width allows it, flat otherwise
    */
    private static void writeScanline(OutputStream os, int[] scanline, int width)
        throws Exception
    {
        if ( width < MINIMUM_ENCODED_SCANLINE_LENGTH || width > MAXIMUM_ENCODED_SCANLINE_LENGTH ) {
            byte[] flat = new byte[BYTES_PER_PIXEL * width];
            for ( int k = 0; k < flat.length; k++ ) {
                flat[k] = (byte)scanline[k];
            }
            writeBytes(os, flat);
            return;
        }

        // A component takes at most 2 bytes per pixel plus one: each run (of at
        // least 2 pixels) takes 2 bytes, and each non-run one byte more than its
        // pixels, with at most one non-run more than runs
        byte[] encoded = new byte[4 + BYTES_PER_PIXEL * (2 * width + 1)];
        int n = 0;

        // Magic header
        encoded[n++] = 2;
        encoded[n++] = 2;
        encoded[n++] = (byte)(width >> 8);
        encoded[n++] = (byte)(width & 255);

        // Components separately
        for ( int i = 0; i < BYTES_PER_PIXEL; i++ ) {
            int count = 0;
            for ( int j = 0; j < width; j += count ) {
                // Find next run
                int begin;
                for ( begin = j; begin < width; begin += count ) {
                    for ( count = 1;
                          count < 127 && begin + count < width
                          && scanline[(begin + count) * BYTES_PER_PIXEL + i] == scanline[begin * BYTES_PER_PIXEL + i];
                          count++ ) {
                    }
                    if ( count >= MINIMUM_RUN_LENGTH ) {
                        // Long enough
                        break;
                    }
                }

                if ( begin - j > 1 && begin - j < MINIMUM_RUN_LENGTH ) {
                    int c2 = j + 1;
                    while ( scanline[(c2++) * BYTES_PER_PIXEL + i] == scanline[j * BYTES_PER_PIXEL + i] ) {
                        if ( c2 == begin ) {
                            // Short run
                            encoded[n++] = (byte)(128 + begin - j);
                            encoded[n++] = (byte)scanline[j * BYTES_PER_PIXEL + i];
                            j = begin;
                            break;
                        }
                    }
                }
                while ( j < begin ) {
                    // Non-run
                    int c2 = begin - j;
                    if ( c2 > 128 ) {
                        c2 = 128;
                    }
                    encoded[n++] = (byte)c2;
                    while ( c2-- > 0 ) {
                        encoded[n++] = (byte)scanline[(j++) * BYTES_PER_PIXEL + i];
                    }
                }
                if ( count >= MINIMUM_RUN_LENGTH ) {
                    // Run
                    encoded[n++] = (byte)(128 + count);
                    encoded[n++] = (byte)scanline[begin * BYTES_PER_PIXEL + i];
                }
                else {
                    count = 0;
                }
            }
        }

        os.write(encoded, 0, n);
    }

    /**
    Writes the image in RGBE format on the given stream (which is not closed).
    Components below zero are written as zero.
    @param os
    @param image
    @return true if the image could be written, false otherwise
    @throws Exception when the stream fails
    */
    public static boolean exportRgbe(OutputStream os, RGBImageFloatUncompressed image)
        throws Exception
    {
        if ( image == null || image.getXSize() <= 0 || image.getYSize() <= 0 ) {
            return false;
        }

        int width = image.getXSize();
        int height = image.getYSize();
        writeHeader(os, width, height);

        int[] scanline = new int[BYTES_PER_PIXEL * width];
        for ( int y = 0; y < height; y++ ) {
            for ( int x = 0; x < width; x++ ) {
                ColorRgb color = image.getPixel(x, y);
                rgbToRgbe(scanline, x * BYTES_PER_PIXEL, color.getR(), color.getG(), color.getB());
            }
            writeScanline(os, scanline, width);
        }
        return true;
    }

    private static boolean readFully(InputStream is, int[] buffer, int offset, int length)
        throws Exception
    {
        for ( int k = 0; k < length; k++ ) {
            int value = is.read();
            if ( value < 0 ) {
                return false;
            }
            buffer[offset + k] = value;
        }
        return true;
    }

    /**
    Reads a header line without its end of line. null at the end of the stream
    or for a line longer than the given capacity.
    */
    private static String readHeaderLine(InputStream is, int capacity)
        throws Exception
    {
        StringBuilder line = new StringBuilder();
        while ( true ) {
            int c = is.read();
            if ( c < 0 ) {
                return null;
            }
            if ( c == '\n' ) {
                break;
            }
            if ( line.length() >= capacity - 1 ) {
                return null;
            }
            line.append((char)c);
        }
        return line.toString();
    }

    /**
    Parses a non negative decimal integer of `line` starting at `position[0]`,
    leaving `position[0]` after its last digit. Returns -1 when there is no
    digit at that position.
    */
    private static int parseInteger(String line, int[] position)
    {
        int p = position[0];
        int sign = 1;
        if ( p < line.length() && (line.charAt(p) == '+' || line.charAt(p) == '-') ) {
            if ( line.charAt(p) == '-' ) {
                sign = -1;
            }
            p++;
        }
        int start = p;
        long value = 0;
        while ( p < line.length() && Character.isDigit(line.charAt(p)) && value <= Integer.MAX_VALUE ) {
            value = value * 10 + (line.charAt(p) - '0');
            p++;
        }
        if ( p == start || value > Integer.MAX_VALUE ) {
            return Integer.MIN_VALUE;
        }
        position[0] = p;
        return (int)(sign * value);
    }

    private static int skipSpaces(String line, int p)
    {
        while ( p < line.length() && Character.isWhitespace(line.charAt(p)) ) {
            p++;
        }
        return p;
    }

    /**
    Reads the header, returning {width, height}, or null if it is not an RGBE
    header with the -Y +X orientation
    */
    private static int[] readHeader(InputStream is)
        throws Exception
    {
        String line = readHeaderLine(is, 1024);
        if ( line == null || !line.startsWith("#?") ) {
            return null;
        }

        // Variables up to the empty line
        while ( true ) {
            line = readHeaderLine(is, 1024);
            if ( line == null ) {
                return null;
            }
            if ( line.isEmpty() ) {
                break;
            }
            if ( line.startsWith("FORMAT=") && !line.substring(7).equals("32-bit_rle_rgbe") ) {
                return null;
            }
        }

        // Resolution: "-Y %d +X %d" with nothing after it
        line = readHeaderLine(is, 1024);
        if ( line == null ) {
            return null;
        }
        int[] position = new int[1];
        int p = skipSpaces(line, 0);
        if ( !line.startsWith("-Y", p) ) {
            return null;
        }
        position[0] = skipSpaces(line, p + 2);
        int height = parseInteger(line, position);
        if ( height == Integer.MIN_VALUE ) {
            return null;
        }
        p = skipSpaces(line, position[0]);
        if ( !line.startsWith("+X", p) ) {
            return null;
        }
        position[0] = skipSpaces(line, p + 2);
        int width = parseInteger(line, position);
        if ( width == Integer.MIN_VALUE || position[0] != line.length() ) {
            return null;
        }
        if ( width <= 0 || height <= 0 ) {
            return null;
        }
        return new int[] {width, height};
    }

    /**
    Reads the rest of a flat scanline, whose first pixel is already in
    `scanline`. As in Radiance, a pixel with r = g = b = 1 after the first one is
    an "old" run length encoded repeat count of the previous pixel (shifted by 8
    bits for each consecutive count).
    */
    private static boolean readOldScanline(InputStream is, int[] scanline, int width)
        throws Exception
    {
        int shift = 0;
        int x = 1;
        while ( x < width ) {
            int pixel = x * BYTES_PER_PIXEL;
            if ( !readFully(is, scanline, pixel, BYTES_PER_PIXEL) ) {
                return false;
            }
            if ( scanline[pixel + RED] == 1 && scanline[pixel + GREEN] == 1 && scanline[pixel + BLUE] == 1 ) {
                long repeat = ((long)scanline[pixel + EXPONENT]) << shift;
                if ( shift > 24 || repeat > width - x ) {
                    return false;
                }
                for ( ; repeat > 0; repeat-- ) {
                    System.arraycopy(scanline, (x - 1) * BYTES_PER_PIXEL, scanline, x * BYTES_PER_PIXEL, BYTES_PER_PIXEL);
                    x++;
                }
                shift += 8;
            }
            else {
                shift = 0;
                x++;
            }
        }
        return true;
    }

    private static boolean readScanline(InputStream is, int[] scanline, int width)
        throws Exception
    {
        if ( width < MINIMUM_ENCODED_SCANLINE_LENGTH || width > MAXIMUM_ENCODED_SCANLINE_LENGTH ) {
            if ( !readFully(is, scanline, 0, BYTES_PER_PIXEL) ) {
                return false;
            }
            return readOldScanline(is, scanline, width);
        }

        int[] start = new int[BYTES_PER_PIXEL];
        if ( !readFully(is, start, 0, BYTES_PER_PIXEL) ) {
            return false;
        }
        if ( start[0] != 2 || start[1] != 2 || (start[2] & 0x80) != 0 ) {
            // Not run length encoded by component: a flat (or old) scanline
            System.arraycopy(start, 0, scanline, 0, BYTES_PER_PIXEL);
            return readOldScanline(is, scanline, width);
        }
        if ( ((start[2] << 8) | start[3]) != width ) {
            return false;
        }

        for ( int i = 0; i < BYTES_PER_PIXEL; i++ ) {
            int x = 0;
            while ( x < width ) {
                int code = is.read();
                if ( code <= 0 ) {
                    return false;
                }
                if ( code > 128 ) {
                    // Run
                    int count = code - 128;
                    int value = is.read();
                    if ( value < 0 || count > width - x ) {
                        return false;
                    }
                    for ( int k = 0; k < count; k++ ) {
                        scanline[(x++) * BYTES_PER_PIXEL + i] = value;
                    }
                }
                else {
                    // Non-run
                    if ( code > width - x ) {
                        return false;
                    }
                    for ( int k = 0; k < code; k++ ) {
                        int value = is.read();
                        if ( value < 0 ) {
                            return false;
                        }
                        scanline[(x++) * BYTES_PER_PIXEL + i] = value;
                    }
                }
            }
        }
        return true;
    }

    /**
    Reads an RGBE image from the given stream (which is not closed).
    @param is
    @return the image, or null if the stream does not hold an RGBE image this
    class can read
    @throws Exception when the stream fails
    */
    public static RGBImageFloatUncompressed importRgbe(InputStream is)
        throws Exception
    {
        int[] size = readHeader(is);
        if ( size == null ) {
            return null;
        }
        int width = size[0];
        int height = size[1];

        RGBImageFloatUncompressed image = new RGBImageFloatUncompressed();
        if ( !image.initNoFill(width, height) ) {
            return null;
        }

        int[] scanline = new int[BYTES_PER_PIXEL * width];
        for ( int y = 0; y < height; y++ ) {
            if ( !readScanline(is, scanline, width) ) {
                return null;
            }
            for ( int x = 0; x < width; x++ ) {
                int pixel = x * BYTES_PER_PIXEL;
                int exponent = scanline[pixel + EXPONENT];
                image.putPixel(
                    x,
                    y,
                    rgbeComponentToDouble(scanline[pixel + RED], exponent),
                    rgbeComponentToDouble(scanline[pixel + GREEN], exponent),
                    rgbeComponentToDouble(scanline[pixel + BLUE], exponent));
            }
        }
        return image;
    }
}
