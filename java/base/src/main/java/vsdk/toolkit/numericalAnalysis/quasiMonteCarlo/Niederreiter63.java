    private static NiederreiterCore core = new NiederreiterCore(
        directionNumbers,
        SKIP,
        NBITS_POW,
        NBITS_POW1,
        DIMEN,
        NBITS);

/**
63bit 4D base-2 Niederreiter quasiMonteCarlo (Quasi Monte Carlo) series,
[CHOW1994] ACM TOMS Algorithm 738, dec 94.

See also:

[BRAT1992] P. Bratley, B. Fox, H. Niederreiter, "Implementation and Tests of
Low-Discrepancy Sequences", ACM Trans Mod Comp Sim Vol 2 Nr 3,
July  1992 p195

Philippe.Bekaert@cs.kuleuven.ac.be, Tue Nov 7 2000
*/
    public static long[] Nied63(long index) {
        return core.sample(index);
    }

    public static long[] NextNiedInRange63(
        long[] idx,
        int dir,
        int nmsb,
        long msb1,
        long rmsb2) {
        return core.nextInRange(idx, dir, nmsb, msb1, rmsb2);
    }

    public static long radicalInverse63(long n) {
        return core.radicalInverse(n);
    }

    public static void foldSample63(long[] xi1, long[] xi2) {
        core.foldSample(xi1, xi2);
    }
